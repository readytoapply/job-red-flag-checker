#!/usr/bin/env node
'use strict';
// Scores the checker on the benchmark (benchmark/cases.json).
//
//   node benchmark/run.js                 the held-out TEST split (the number we publish)
//   node benchmark/run.js --split dev     the split rules may be tuned on
//   node benchmark/run.js --split all
//   node benchmark/run.js --misses        list the cases it gets wrong (ids + verdict)
//   node benchmark/run.js --write         also write benchmark/RESULTS.md
//
// Rules are tuned on "dev" only. "test" is scored, never tuned on: that is
// what makes its numbers an honest estimate rather than a self-graded one.
const fs = require('fs');
const path = require('path');
const RF = require('../src/red-flags.js');

const arg = (n, d) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : d; };
const SPLIT = arg('--split', 'test');
// --file cases-r2.json scores another round's held-out set.
const FILE = arg('--file', 'cases.json');
const cases = JSON.parse(fs.readFileSync(path.join(__dirname, FILE), 'utf8'))
  .filter((c) => SPLIT === 'all' || c.split === SPLIT);

const WARN = ['stop', 'high', 'caution'];
const pct = (a, b) => (b ? (100 * a / b).toFixed(1) + '%' : '–');
const results = cases.map((c) => {
  const r = RF.scan(c.text);
  return { c, level: r.verdict.level, found: r.found };
});
const scams = results.filter((x) => x.c.label === 'scam');
const legit = results.filter((x) => x.c.label === 'legit');
const n = (arr, levels) => arr.filter((x) => levels.includes(x.level)).length;

const s = {
  scams: scams.length, legit: legit.length,
  scamStop: n(scams, ['stop']), scamHigh: n(scams, ['stop', 'high']), scamWarn: n(scams, WARN),
  scamAny: scams.filter((x) => x.found.length).length,
  legitStop: n(legit, ['stop']), legitHigh: n(legit, ['stop', 'high']), legitWarn: n(legit, WARN),
  legitAny: legit.filter((x) => x.found.length).length
};

// Per scam type: how often it gets a warning (caution or worse).
const byType = {};
results.forEach((x) => {
  const k = x.c.label + ':' + x.c.type;
  const t = byType[k] = byType[k] || { label: x.c.label, type: x.c.type, n: 0, warn: 0, stop: 0 };
  t.n++;
  if (WARN.includes(x.level)) t.warn++;
  if (x.level === 'stop') t.stop++;
});

// Per flag: how often it fires on scams vs real jobs.
const perFlag = RF.flags().map((f) => {
  const onScam = scams.filter((x) => x.found.includes(f.id)).length;
  const onLegit = legit.filter((x) => x.found.includes(f.id)).length;
  return { f, onScam, onLegit };
});

const lines = [];
const out = (l) => lines.push(l);
out('Job Red Flag Checker v' + RF.version + ' · ' + FILE + ' · split: ' + SPLIT + ' · ' + cases.length + ' cases (' + s.scams + ' scams, ' + s.legit + ' real jobs)');
out('');
out('Scams that get a warning (caution or worse):   ' + s.scamWarn + ' of ' + s.scams + '  (' + pct(s.scamWarn, s.scams) + ')');
out('Scams that get "Stop" or "Walk away":          ' + s.scamHigh + ' of ' + s.scams + '  (' + pct(s.scamHigh, s.scams) + ')');
out('Scams with at least one flag:                  ' + s.scamAny + ' of ' + s.scams + '  (' + pct(s.scamAny, s.scams) + ')');
out('Real jobs wrongly told "Stop":                 ' + s.legitStop + ' of ' + s.legit + '  (' + pct(s.legitStop, s.legit) + ')');
out('Real jobs given any warning:                   ' + s.legitWarn + ' of ' + s.legit + '  (' + pct(s.legitWarn, s.legit) + ')');
out('Real jobs with at least one flag:              ' + s.legitAny + ' of ' + s.legit + '  (' + pct(s.legitAny, s.legit) + ')');
out('');
out('By type                                          cases   warned    stop');
Object.values(byType).sort((a, b) => (a.label + a.type).localeCompare(b.label + b.type)).forEach((t) => {
  out('  ' + (t.label + ' · ' + t.type).padEnd(46) + String(t.n).padStart(6) + String(t.warn).padStart(9) + String(t.stop).padStart(8));
});
out('');
out('By flag                                 on scams   on real jobs');
perFlag.forEach(({ f, onScam, onLegit }) => out('  ' + (f.tier + ' · ' + f.id).padEnd(38) + String(onScam).padStart(9) + String(onLegit).padStart(15)));
console.log(lines.join('\n'));

if (process.argv.includes('--misses')) {
  console.log('\nMissed scams (no warning):');
  scams.filter((x) => !WARN.includes(x.level)).forEach((x) => console.log('  ' + x.c.id + ' [' + x.c.type + '] ' + x.level + (x.found.length ? ' · ' + x.found.join(', ') : '')));
  console.log('\nReal jobs given a warning:');
  legit.filter((x) => WARN.includes(x.level)).forEach((x) => console.log('  ' + x.c.id + ' [' + x.c.type + '] ' + x.level + ' · ' + x.found.join(', ')));
}

if (process.argv.includes('--write')) {
  const md = [
    '# Benchmark results',
    '',
    '_Generated by `node benchmark/run.js --write` on ' + new Date().toISOString().slice(0, 10) + ', checker v' + RF.version + ', `' + FILE + '`, split **' + SPLIT + '**. Do not edit by hand._',
    '',
    '> These are **synthetic cases** written by an AI assistant from public descriptions of job scams (FTC, FBI IC3, BBB, the Canadian Anti-Fraud Centre, Scamwatch and others), **held out from rule tuning**. They are not postings collected in the wild. See METHODOLOGY.md.',
    '',
    '| | Result |',
    '|---|---|',
    '| Scams that get a warning (caution or worse) | **' + s.scamWarn + ' of ' + s.scams + ' (' + pct(s.scamWarn, s.scams) + ')** |',
    '| Scams that get "Stop" or "Walk away" | ' + s.scamHigh + ' of ' + s.scams + ' (' + pct(s.scamHigh, s.scams) + ') |',
    '| Real jobs wrongly told "Stop" | **' + s.legitStop + ' of ' + s.legit + ' (' + pct(s.legitStop, s.legit) + ')** |',
    '| Real jobs given any warning | ' + s.legitWarn + ' of ' + s.legit + ' (' + pct(s.legitWarn, s.legit) + ') |',
    '',
    '## By type',
    '',
    '| Label | Type | Cases | Warned | Stop |',
    '|---|---|---:|---:|---:|',
    ...Object.values(byType).sort((a, b) => (a.label + a.type).localeCompare(b.label + b.type))
      .map((t) => '| ' + t.label + ' | ' + t.type + ' | ' + t.n + ' | ' + t.warn + ' | ' + t.stop + ' |'),
    '',
    '## By flag',
    '',
    '| Tier | Flag | Fires on scams | Fires on real jobs |',
    '|---|---|---:|---:|',
    ...perFlag.map(({ f, onScam, onLegit }) => '| ' + f.tier + ' | ' + f.label + ' | ' + onScam + ' | ' + onLegit + ' |'),
    '',
    'How the benchmark was built and why the split matters: [METHODOLOGY.md](../METHODOLOGY.md).',
    ''
  ].join('\n');
  fs.writeFileSync(path.join(__dirname, 'RESULTS.md'), md);
  console.log('\nwrote benchmark/RESULTS.md');
}
